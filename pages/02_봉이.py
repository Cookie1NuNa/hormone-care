# --- 1. 구글 시트 및 데이터 기본 설정 ---
conn = st.connection("gsheets", type=GSheetsConnection)

def load_user_data():
    try:
        df = conn.read()
        # "봉이"를 찾아라! 🕵️‍♀️
        user_row = df[df['name'] == "봉이"] 
        if not user_row.empty:
            return user_row.iloc[0]['date']
    except:
        pass
    return str(datetime.date.today()) 

def save_user_data(date_str):
    df = conn.read()
    # "봉이" 자리에 저장! 💾
    if "봉이" in df['name'].values:
        df.loc[df['name'] == "봉이", 'date'] = date_str
    else:
        # 새로 만들 때도 주기를 31일로 설정!
        new_row = pd.DataFrame([{"name": "봉이", "date": date_str, "cycle": 31}])
        df = pd.concat([df, new_row], ignore_index=True)
    conn.update(data=df)
    st.cache_data.clear()

# 주기는 봉이에게 딱 맞춘 31일로 고정! 🗓️
def calculate_cycle_day(start_date_str):
    try:
        start_date = datetime.datetime.strptime(start_date_str, "%Y-%m-%d").date()
        today = datetime.date.today()
        delta = today - start_date
        # 28 대신 31로 나눠줘야 봉이 주기에 딱 맞게 돌아가!
        return (delta.days % 31) + 1
    except:
        return None

